def norm_place(s) -> str:
    """یکسان‌سازی نام استان/شهر: حروف عربی→فارسی، نیم‌فاصله→فاصله، فاصله‌های تکراری."""
    s = str(s or "").strip()
    s = s.replace("ي", "ی").replace("ك", "ک").replace("أ", "ا").replace("إ", "ا")
    s = s.replace("\u200c", " ")
    return " ".join(s.split())


