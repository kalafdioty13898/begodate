def detect_intent(text: str):
    t = (text or "").lower().strip()
    for cat, kws in INTENT_KEYWORDS:
        for kw in kws:
            if kw in t:
                return cat
    if t.endswith("؟") or t.endswith("?"):
        return "question"
    return "smalltalk"


def _fill(template: str, user: dict) -> str:
    gender_word = "دختر" if user.get("gender") == "F" else "پسر"
    return (template.replace("{name}", str(user.get("nickname") or ""))
                    .replace("{age}", str(user.get("age") or ""))
                    .replace("{city}", str(user.get("city") or ""))
                    .replace("{province}", str(user.get("province") or ""))
                    .replace("{hobby}", str(random.choice(HOBBY_FILLERS)))
                    .replace("{gender}", gender_word))


def generate_reply(test_user: dict, category: str, last_reply=None) -> str:
    """انتخاب پاسخ تصادفی بدون تکرار پاسخ قبلی."""
    pool = CATEGORIES.get(category) or SMALLTALK
    text = ""
    for _ in range(8):
        text = _fill(random.choice(pool), test_user)
        if text != (last_reply or ""):
            break
    return text


def dataset_size() -> int:
    return sum(len(v) for v in CATEGORIES.values())


